// The manifest is an operator's explicit scope, not cryptographic proof that a
// project is staging. Independently verify branch identity before using it.
export function validateManifest(manifest, tree, now = Date.now()) {
  assert.equal(manifest?.contract, 'public-hosted-acceptance-v1');
  assert.equal(manifest.scope, 'isolated-staging');
  assert.match(manifest.projectRef ?? '', /^[a-z]{20}$/);
  assert.ok(!protectedProjects.has(manifest.projectRef));
  assert.match(manifest.candidateTree ?? '', sha);
  assert.equal(manifest.candidateTree, tree);
  const expires = Date.parse(manifest.expiresAt);
  assert.ok(expires > now && expires - now <= 24 * 60 * 60 * 1000);
  assert.equal(manifest.syntheticWritesApproved, true);
  assert.equal(manifest.branchIdentityVerified, true);
  assert.equal(manifest.accounts?.length, 2);
  for (const account of manifest.accounts) {
    assert.match(account.authUserId ?? '', uuid);
    assert.match(account.personId ?? '', uuid);
  }
  assert.notEqual(manifest.accounts[0].authUserId, manifest.accounts[1].authUserId);
  assert.notEqual(manifest.accounts[0].personId, manifest.accounts[1].personId);
  return `https://${manifest.projectRef}.supabase.co`;
}

export function validatePublicKey(key) {
  assert.equal(typeof key, 'string');
  assert.ok(key.length < 5000);
  if (/^sb_publishable_[A-Za-z0-9_-]+$/.test(key)) return key;
  const parts = key.split('.');
  assert.equal(parts.length, 3);
  const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
  assert.equal(payload.role, 'anon');
  return key;
}

export async function cleanupArtifacts(owner, ids) {
  const failures = [];
  const attempt = async (name, action) => {
    try {
      assert.equal((await action()).error, null);
    } catch {
      failures.push(name);
    }
  };
  // IDs are only generated by this run or resolved through its exact source turn.
  // Recover uncertain creates by source identity; never enumerate unrelated work.
  await attempt('deliverables', async () => {
    const found = await owner
      .from('mission_deliverables')
      .select('id,revision')
      .eq('source_mission_id', ids.mission)
      .eq('source_turn_id', ids.turn);
    assert.equal(found.error, null);
    for (const row of found.data) {
      assert.equal(
        (
          await owner.rpc('mission_delete_deliverable', {
            p_id: row.id,
            p_expected: row.revision,
          })
        ).error,
        null,
      );
    }
    return { error: null };
  });
  if (!ids.studio) {
    await attempt('studio-link', async () => {
      const found = await owner
        .from('mission_studio_links')
        .select('project_id')
        .eq('mission_id', ids.mission)
        .maybeSingle();
      assert.equal(found.error, null);
      ids.studio = found.data?.project_id;
      return { error: null };
    });
  }
  await attempt('storage', async () => {
    const removed = await owner.storage
      .from(bucket)
      .remove([ids.storage, ids.storage.replace('.png', '-forged.png')]);
    assert.equal(removed.error, null);
    const remaining = await owner.storage.from(bucket).list(ids.storage.split('/')[0], {
      search: ids.storage.split('/')[1].replace('.png', ''),
      limit: 2,
    });
    assert.equal(remaining.error, null);
    assert.equal(remaining.data.length, 0);
    return { error: null };
  });
  await attempt('mission', () =>
    owner.from('intelligence_missions').delete().eq('id', ids.mission),
  );
  await attempt('conversation', () => owner.from('ai_conversations').delete().eq('id', ids.thread));
  if (ids.studio)
    await attempt('studio', () => owner.from('ai_studio_projects').delete().eq('id', ids.studio));
  return failures;
}

export async function runAcceptance(owner, other, anon, accounts, report) {
  const ids = {
    mission: crypto.randomUUID(),
    thread: crypto.randomUUID(),
    turn: crypto.randomUUID(),
  };
  ids.storage = `${accounts[0].authUserId}/${crypto.randomUUID()}.png`;
  let stage = 'identity';
  const complete = () => report.checks.push({ check: stage, status: 'passed' });
  const denied = (result, code = '42501') => assert.equal(result.error?.code, code);
  try {
    for (const [client, account] of [
      [owner, accounts[0]],
      [other, accounts[1]],
    ]) {
      const user = await client.auth.getUser();
      assert.equal(user.error, null);
      assert.equal(user.data.user.id, account.authUserId);
      const person = await client.from('persons').select('id,auth_user_id').single();
      assert.equal(person.error, null);
      assert.equal(person.data.id, account.personId);
      assert.equal(person.data.auth_user_id, account.authUserId);
    }
    complete();
    stage = 'mission-context';
    assert.equal(
      (
        await owner.rpc('ai_begin_turn', {
          p_conversation: ids.thread,
          p_request: ids.turn,
          p_text: 'Synthetic acceptance objective',
          p_model: 'synthetic-no-model-call',
          p_context: false,
          p_prompt_version: 'hosted-acceptance-v1',
        })
      ).error,
      null,
    );
    assert.equal(
      (
        await owner.from('intelligence_missions').insert({
          id: ids.mission,
          person_id: accounts[0].personId,
          conversation_id: ids.thread,
          title: 'Synthetic acceptance project',
          objective: 'Verify saved work',
          status: 'active',
          decisions: 'Synthetic records only',
          next_actions: 'Review the document',
        })
      ).error,
      null,
    );
    const capture = { p_turn: ids.turn, p_mission: ids.mission, p_revision: 1 };
    const captured = await owner.rpc('mission_capture_context', capture);
    assert.equal(captured.error, null);
    assert.equal(captured.data.objective, 'Verify saved work');
    denied(await other.rpc('mission_capture_context', capture));
    denied(await owner.rpc('mission_capture_context', { ...capture, p_revision: 2 }), '22023');
    assert.equal(
      (
        await owner.rpc('ai_finish_turn', {
          p_request: ids.turn,
          p_text: 'Synthetic saved work product',
          p_status: 'complete',
          p_input: 0,
          p_output: 0,
        })
      ).data,
      true,
    );
    complete();
    stage = 'deliverable-replay-isolation';
    const create = { p_mission: ids.mission, p_turn: ids.turn, p_revision: 1 };
    const created = await owner.rpc('mission_create_deliverable', create);
    assert.equal(created.error, null);
    ids.document = created.data;
    assert.match(ids.document, uuid);
    assert.equal((await owner.rpc('mission_create_deliverable', create)).data, ids.document);
    denied(await other.rpc('mission_create_deliverable', create));
    const hidden = await other
      .from('mission_deliverable_versions')
      .select('id')
      .eq('deliverable_id', ids.document);
    assert.equal(hidden.error, null);
    assert.equal(hidden.data.length, 0);
    denied(await anon.from('mission_deliverables').select('id'));
    complete();
    stage = 'immutable-version-review';
    const version = crypto.randomUUID();
    const save = {
      p_id: ids.document,
      p_version: version,
      p_expected: 1,
      p_title: 'Synthetic revised document',
      p_body: 'Explicitly revised synthetic work',
      p_acceptance: 'Verify title and content',
    };
    assert.equal((await owner.rpc('mission_save_deliverable', save)).error, null);
    assert.equal((await owner.rpc('mission_save_deliverable', save)).error, null);
    denied(
      await owner.rpc('mission_save_deliverable', { ...save, p_version: crypto.randomUUID() }),
      '40001',
    );
    denied(await other.rpc('mission_save_deliverable', save));
    denied(
      await owner
        .from('mission_deliverable_versions')
        .update({ body: 'Forbidden' })
        .eq('id', version),
    );
    const review = { p_id: ids.document, p_version: version, p_note: 'Synthetic content checked' };
    assert.equal((await owner.rpc('mission_review_deliverable', review)).error, null);
    const versions = await owner
      .from('mission_deliverable_versions')
      .select('id,revision,body,reviewed_at')
      .eq('deliverable_id', ids.document)
      .order('revision');
    assert.equal(versions.error, null);
    assert.equal(versions.data.length, 2);
    assert.equal(versions.data[0].body, 'Synthetic saved work product');
    assert.ok(versions.data[1].reviewed_at);
    assert.equal((await owner.rpc('mission_review_deliverable', review)).error, null);
    const reread = await owner
      .from('mission_deliverable_versions')
      .select('reviewed_at')
      .eq('id', version)
      .single();
    assert.equal(reread.error, null);
    assert.equal(reread.data.reviewed_at, versions.data[1].reviewed_at);
    complete();
    stage = 'studio-detached-work';
    const studio = await owner.rpc('mission_open_studio', {
      p_mission: ids.mission,
      p_revision: 1,
    });
    assert.equal(studio.error, null);
    ids.studio = studio.data;
    assert.equal(
      (await owner.rpc('mission_open_studio', { p_mission: ids.mission, p_revision: 1 })).data,
      ids.studio,
    );
    denied(await other.rpc('mission_open_studio', { p_mission: ids.mission, p_revision: 1 }));
    assert.equal(
      (await owner.from('intelligence_missions').delete().eq('id', ids.mission)).error,
      null,
    );
    const retained = await owner
      .from('mission_deliverable_summaries')
      .select('mission_id,revision')
      .eq('id', ids.document)
      .single();
    assert.equal(retained.error, null);
    assert.equal(retained.data.mission_id, null);
    assert.equal(retained.data.revision, 2);
    const retainedStudio = await owner
      .from('ai_studio_projects')
      .select('id')
      .eq('id', ids.studio)
      .single();
    assert.equal(retainedStudio.error, null);
    assert.equal(retainedStudio.data.id, ids.studio);
    denied(await other.rpc('mission_delete_deliverable', { p_id: ids.document, p_expected: 2 }));
    complete();
    stage = 'private-storage';
    assert.equal(
      (
        await owner.storage
          .from(bucket)
          .upload(ids.storage, image, { contentType: 'image/png', upsert: false })
      ).error,
      null,
    );
    const downloaded = await owner.storage.from(bucket).download(ids.storage);
    assert.equal(downloaded.error, null);
    assert.deepEqual(Buffer.from(await downloaded.data.arrayBuffer()), image);
    // Expected access denials only: transport/server failures must not pass.
    for (const client of [other, anon]) {
      for (const result of [
        await client.storage.from(bucket).download(ids.storage),
        await client.storage.from(bucket).createSignedUrl(ids.storage, 30),
      ]) {
        assert.ok(result.error);
        assert.ok(['400', '403', '404'].includes(String(result.error.statusCode)));
        assert.equal(result.data, null);
      }
    }
    // Private-bucket RLS alone cannot detect an accidentally public endpoint.
    const publicUrl = anon.storage.from(bucket).getPublicUrl(ids.storage).data.publicUrl;
    const publicResponse = await fetch(publicUrl, {
      redirect: 'error',
      signal: AbortSignal.timeout(10000),
    });
    await publicResponse.body?.cancel();
    assert.ok([400, 403, 404].includes(publicResponse.status));
    const forged = await other.storage
      .from(bucket)
      .upload(ids.storage.replace('.png', '-forged.png'), image, { contentType: 'image/png' });
    assert.ok(forged.error);
    assert.ok(['400', '403'].includes(String(forged.error.statusCode)));
    // Remove can return an empty success under RLS; verify the owner's bytes survive.
    await other.storage.from(bucket).remove([ids.storage]);
    const after = await owner.storage.from(bucket).download(ids.storage);
    assert.equal(after.error, null);
    assert.deepEqual(Buffer.from(await after.data.arrayBuffer()), image);
    complete();
  } catch {
    report.checks.push({ check: stage, status: 'failed' });
  } finally {
    report.cleanupFailures =
      report.checks[0]?.status === 'passed' ? await cleanupArtifacts(owner, ids) : [];
    report.cleanupStatus =
      report.checks[0]?.status !== 'passed'
        ? 'not-started'
        : report.cleanupFailures.length
          ? 'incomplete'
          : 'complete';
    if (report.cleanupFailures.length) report.recoveryIds = ids;
  }
  report.status =
    report.checks.length === 6 &&
    report.checks.every((c) => c.status === 'passed') &&
    report.cleanupStatus === 'complete'
      ? 'passed'
      : 'failed';
  return report;
}

async function main(args) {
  await verifyMigrationFiles();
  const tree = execFileSync('git', ['rev-parse', 'HEAD^{tree}'], {
    cwd: root,
    encoding: 'utf8',
  }).trim();
  assert.equal(
    execFileSync('git', ['status', '--porcelain', '--untracked-files=no'], {
      cwd: root,
      encoding: 'utf8',
    }).trim(),
    '',
  );
  let url, key, accounts, logins, scope, projectRef;
  if (args.length === 1 && args[0] === '--local') {
    const env = Object.fromEntries(
      (await readFile(resolve(root, '.env.development.local'), 'utf8'))
        .trim()
        .split('\n')
        .map((line) => {
          const i = line.indexOf('=');
          return [line.slice(0, i), line.slice(i + 1)];
        }),
    );
    assert.equal(env.NEXT_PUBLIC_SUPABASE_URL, 'http://127.0.0.1:54321');
    url = env.NEXT_PUBLIC_SUPABASE_URL;
    key = validatePublicKey(env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY);
    logins = ['member@aurelius.test', 'founder@aurelius.test'].map((email) => ({
      email,
      password: env.AURELIUS_FOUNDER_PASSWORD,
    }));
    scope = 'disposable-local';
    projectRef = null;
  } else {
    assert.equal(args.length, 2);
    assert.equal(args[0], '--staging');
    const bytes = await readFile(args[1], 'utf8');
    assert.ok(bytes.length < 10000);
    const manifest = JSON.parse(bytes);
    url = validateManifest(manifest, tree);
    projectRef = manifest.projectRef;
    accounts = manifest.accounts;
    key = validatePublicKey(process.env.ACCEPTANCE_PUBLISHABLE_KEY);
    logins = ['A', 'B'].map((label) => ({
      email: process.env[`ACCEPTANCE_${label}_EMAIL`],
      password: process.env[`ACCEPTANCE_${label}_PASSWORD`],
    }));
    assert.ok(logins.every((login) => login.email && login.password));
    assert.notEqual(logins[0].email.toLowerCase(), logins[1].email.toLowerCase());
    scope = 'isolated-staging';
  }
  // Redirects cannot move credentials off the scoped host; every request is bounded.
  const client = () =>
    createClient(url, key, {
      auth: { persistSession: false, autoRefreshToken: false },
      global: {
        fetch: (input, init) =>
          fetch(input, { ...init, redirect: 'error', signal: AbortSignal.timeout(10000) }),
      },
    });
  const owner = client(),
    other = client(),
    anon = client();
  for (const [client, login] of [
    [owner, logins[0]],
    [other, logins[1]],
  ])
    assert.equal((await client.auth.signInWithPassword(login)).error, null);
  if (!accounts) {
    accounts = [];
    for (const client of [owner, other]) {
      const person = await client.from('persons').select('id,auth_user_id').single();
      assert.equal(person.error, null);
      accounts.push({ personId: person.data.id, authUserId: person.data.auth_user_id });
    }
  }
  const report = await runAcceptance(owner, other, anon, accounts, {
    contract: 'public-hosted-acceptance-v1',
    scope,
    projectRef,
    candidateTree: tree,
    observedAt: new Date().toISOString(),
    checks: [],
    releaseApproved: false,
    excluded: [
      'migration-ledger/catalog acceptance',
      'application/browser exports',
      'live model',
      'physical devices',
      'billing',
    ],
  });
  const output = resolve(root, 'test-results/public-account-acceptance.json');
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, `${JSON.stringify(report, null, 2)}\n`, { mode: 0o600 });
  console.log(JSON.stringify(report, null, 2));
  if (report.status !== 'passed') process.exitCode = 1;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch(() => {
    console.error(
      'Acceptance could not complete. Check the scoped manifest, candidate, credentials and services; no private error details are logged.',
    );
    process.exitCode = 1;
  });
}
